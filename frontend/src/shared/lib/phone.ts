// shared/lib/phone.ts
// ─────────────────────────────────────────────────────────────
// 전화번호 포맷팅 유틸
//
// DB 저장 규칙:
//   숫자만 저장. 예: "01012345678"
//   하이픈, 공백 등은 저장하지 않음.
//
// 화면 표시 규칙:
//   입력 중에는 자동으로 하이픈 삽입. 예: "010-1234-5678"
//   UX를 위해 입력할 때만 포맷팅하고, 전송 시에는 숫자만 추출.
//
// 왜 숫자만 저장하나?
// - 유저마다 "010-1234-5678", "010 1234 5678", "01012345678" 등
//   다른 형식으로 입력할 수 있음
// - DB에 형식이 다르면 이메일 찾기(전화번호 검색)에서 못 찾을 수 있음
// - 숫자만 저장하면 어떤 형식으로 입력해도 동일한 값으로 저장/검색됨

// ─────────────────────────────────────────────────────────────
// 숫자만 추출
//
// 입력값에서 숫자가 아닌 문자를 전부 제거.
// DB 저장, API 전송 시 사용.
//
// 예시:
//   "010-1234-5678" → "01012345678"
//   "010 1234 5678" → "01012345678"
//   "01012345678"   → "01012345678"
// ─────────────────────────────────────────────────────────────
export function stripPhone(value: string): string {
  return value.replace(/\D/g, "");
}

// ─────────────────────────────────────────────────────────────
// 화면 표시용 포맷팅
//
// 숫자를 입력하면 자동으로 하이픈을 넣어서
// "010-1234-5678" 형태로 보여줌.
//
// 동작:
//   "010"       → "010"
//   "0101"      → "010-1"
//   "0101234"   → "010-1234"
//   "01012345678" → "010-1234-5678"
//
// 한국 휴대전화 번호 형식 기준 (3-4-4).
// 입력 중에 실시간으로 호출됨.
// ─────────────────────────────────────────────────────────────
export function formatPhone(value: string): string {
  // 먼저 숫자만 추출
  const digits = stripPhone(value);

  // 최대 11자리까지만 허용 (01012345678)
  const limited = digits.slice(0, 11);

  // 자릿수에 따라 하이픈 삽입
  if (limited.length <= 3) {
    // "010" 이하 → 그대로
    return limited;
  }

  if (limited.length <= 7) {
    // "0101" ~ "0101234" → "010-1" ~ "010-1234"
    return `${limited.slice(0, 3)}-${limited.slice(3)}`;
  }

  // "01012345" ~ "01012345678" → "010-1234-5" ~ "010-1234-5678"
  return `${limited.slice(0, 3)}-${limited.slice(3, 7)}-${limited.slice(7)}`;
}